    public void criarLabelImagens(int x, int y, int largura, int altura, JLabel label, ImageIcon imagem) {
        label.setText("  ");
        label.setOpaque(false);
        label.setBounds(x, y, largura, altura);
        label.setBorder(BorderFactory.createLineBorder(Color.RED, 2));

        Image imagemRedimensionada = imagem.getImage()
                .getScaledInstance(200, 550, Image.SCALE_SMOOTH);
//        label.setHorizontalAlignment(JLabel.CENTER);
        label.setIcon(new ImageIcon(imagemRedimensionada));
    }

    public void criarLabel(int x, int y, int largura, int altura, JLabel label, String op) {
        label.setText("  ");
        label.setOpaque(false);
        label.setBounds(x, y, largura, altura);
//        label.setBounds(x, y, 232, 90);
        label.addMouseListener(new MouseAdapter() {

            @Override
            public void mouseEntered(MouseEvent e) {
                setCursor(new Cursor(Cursor.HAND_CURSOR));
            }

            @Override
            public void mouseExited(MouseEvent e) {
                setCursor(new Cursor(Cursor.DEFAULT_CURSOR));
            }

            @Override
            public void mouseClicked(MouseEvent e) {
                switch (op) {
                    case "jogar":
                        dispose();
                        new Maison_2_Velvet_Escolha_Inicial(true, new Boneca()).setVisible(true);
                        break;
                    case "sair":
                        System.exit(0);
                        break;
                }
            }
        });
    }
    
    public void mostrarBoneca(Boneca boneca) {
        int novoX = 560; 
        int novoY = -70; 

        JLabel pele = boneca.getPele();
        if (pele == null) return;

     
        int deltaX = novoX - pele.getX();
        int deltaY = novoY - pele.getY();


        JLabel[] pecas = {
            boneca.getCabelo(),
            boneca.getBolsa(),
            boneca.getAcessorio(),
            boneca.getRoupaS(),
            boneca.getRoupaI(),
            boneca.getVestido(),
            boneca.getConjunto(),
            boneca.getSapato(),
            pele
        };

        for (JLabel peca : pecas) {
            if (peca != null) {
                peca.setLocation(peca.getX() + deltaX, peca.getY() + deltaY);
                this.add(peca);
            }
        }

        revalidate();
        repaint();
    }

